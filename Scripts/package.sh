#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
DEST="${1:-$ROOT/.build/releases}"
mkdir -p "$DEST"
DEST="$(cd "$DEST" && pwd)"
STAGE="$(mktemp -d "${TMPDIR:-/tmp/}folderpreview-release.XXXXXX")"
trap 'rm -rf "$STAGE"' EXIT
KIT="$STAGE/FolderPreviewDroplet-1.0.0"
mkdir -p "$KIT"
BUNDLE="$KIT/FolderPreviewDroplet.droplet"
APP="$KIT/Folder Preview Droplet.app"
ditto --norsrc --noextattr "$ROOT/.build/native/Folder Preview Droplet.app" "$APP"
ditto --norsrc --noextattr "$ROOT/.build/FolderPreviewDroplet.droplet" "$BUNDLE"
rm -rf "$BUNDLE/Contents/Resources/Assets/Companion/Folder Preview Droplet.app"
ditto --norsrc --noextattr "$APP" "$BUNDLE/Contents/Resources/Assets/Companion/Folder Preview Droplet.app"
cp droplet.json "$BUNDLE/Contents/Resources/droplet.json"
xattr -cr "$KIT"
chflags -R nohidden "$KIT"
codesign --verify --deep --strict "$APP"
codesign --force --sign "${SIGN_IDENTITY:--}" "$BUNDLE"
codesign --verify --deep --strict "$BUNDLE"
cp docs/INSTALLATION.txt "$KIT/Installation.txt"
cp LICENSE "$KIT/LICENSE"
ditto -c -k --norsrc --noextattr --keepParent "$BUNDLE" "$DEST/FolderPreviewDroplet-1.0.0.droplet.zip"
ditto -c -k --norsrc --noextattr --keepParent "$KIT" "$DEST/FolderPreviewDroplet-1.0.0-macOS.zip"
(cd "$DEST" && shasum -a 256 FolderPreviewDroplet-1.0.0.droplet.zip FolderPreviewDroplet-1.0.0-macOS.zip > SHA256SUMS.txt)
echo "Packages: $DEST"
